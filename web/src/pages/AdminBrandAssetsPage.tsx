import { useQuery } from "@tanstack/react-query";
import { Image, Phone, Type } from "lucide-react";
import { brandAssetsApi } from "../api/brandAssets";
import { BrandAssetUploader } from "../components/admin/BrandAssetUploader";
import { Spinner } from "../components/common/Spinner";

export function AdminBrandAssetsPage() {
  const { data: assets, isLoading } = useQuery({
    queryKey: ["brand-assets"],
    queryFn: brandAssetsApi.list,
  });

  const byKind = Object.fromEntries((assets ?? []).map((a) => [a.kind, a]));

  return (
    <div className="space-y-6">
      <div className="flex items-center gap-3">
        <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-gradient-to-br from-brand-primary to-brand-secondary shadow-sm">
          <Image className="h-5 w-5 text-white" aria-hidden="true" />
        </div>
        <div>
          <h1 className="font-serif text-xl font-semibold text-brand-primary">Brand assets</h1>
          <p className="mt-1 text-sm text-neutral-500">
            The logo, tagline, and footer are never generated by the image model — they're composited from these files
            on every poster.
          </p>
        </div>
      </div>

      {isLoading ? (
        <Spinner label="Loading brand assets..." />
      ) : (
        <div className="grid gap-4 sm:grid-cols-3">
          <BrandAssetUploader kind="logo" label="Logo" hint="PNG with transparency." icon={Image} current={byKind.logo} />
          <BrandAssetUploader kind="tagline" label="Tagline lockup" hint="PNG with transparency." icon={Type} current={byKind.tagline} />
          <BrandAssetUploader kind="footer" label="Footer icon" hint="Phone icon placed on the footer bar." icon={Phone} current={byKind.footer} />
        </div>
      )}
    </div>
  );
}
